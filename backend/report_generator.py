def draw_header_footer(canvas, doc):

    canvas.saveState()

    width, height = doc.pagesize

    # Header Bar

    canvas.setFillColor(PRIMARY)

    canvas.rect(
        0,
        height - 45,
        width,
        45,
        fill=1,
        stroke=0
    )

    canvas.setFillColor(colors.white)

    canvas.setFont(
        "Helvetica-Bold",
        18
    )

    canvas.drawString(
        40,
        height - 28,
        "AI Voice Scam Detection System"
    )

    # Footer Line

    canvas.setStrokeColor(PRIMARY)

    canvas.line(
        35,
        30,
        width - 35,
        30
    )

    canvas.setFont(
        "Helvetica",
        9
    )

    canvas.setFillColor(colors.grey)

    canvas.drawString(
        40,
        15,
        "Generated by AI Voice Scam Detection System"
    )

    canvas.drawRightString(
        width - 40,
        15,
        f"Page {doc.page}"
    )

    canvas.restoreState()


