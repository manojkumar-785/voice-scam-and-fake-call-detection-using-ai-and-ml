import jsPDF from "jspdf";

export const generateReport = (result: any) => {

  const doc = new jsPDF();

  /* -----------------------
     Cover
  ----------------------- */

  doc.setFillColor(37,99,235);

  doc.rect(0,0,210,40,"F");

  doc.setTextColor(255,255,255);

  doc.setFontSize(24);

  doc.text(
    "AI Voice Scam Detection",
    20,
    22
  );

  doc.setFontSize(13);

  doc.text(
    "Professional Analysis Report",
    20,
    32
  );

  /* -----------------------
     Summary
  ----------------------- */

  doc.setTextColor(0,0,0);

  doc.setFontSize(18);

  doc.text(
    "Analysis Summary",
    20,
    55
  );

  doc.setFontSize(12);

  doc.text(
    `Prediction : ${result.prediction}`,
    20,
    70
  );

  doc.text(
    `Confidence : ${result.confidence}%`,
    20,
    80
  );

  doc.text(
    `Risk Level : ${result.risk_level}`,
    20,
    90
  );

  doc.text(
    `Generated : ${new Date().toLocaleString()}`,
    20,
    100
  );

  /* -----------------------
     Transcript
  ----------------------- */

  doc.setFontSize(16);

  doc.text(
    "Transcript",
    20,
    120
  );

  doc.setFontSize(11);

  const transcript =
    doc.splitTextToSize(
      result.transcript,
      170
    );

  doc.text(
    transcript,
    20,
    130
  );

  let y =
    135 +
    transcript.length * 6;

  /* -----------------------
     Keywords
  ----------------------- */

  doc.setFontSize(16);

  doc.text(
    "Detected Keywords",
    20,
    y
  );

  y += 10;

  doc.setFontSize(11);

  doc.text(
    result.keywords?.join(", ") || "None",
    20,
    y
  );

  y += 18;

  /* -----------------------
     AI Reasons
  ----------------------- */

  doc.setFontSize(16);

  doc.text(
    "Why AI Predicted This",
    20,
    y
  );

  y += 10;

  doc.setFontSize(11);

  result.reasons?.forEach((item:string)=>{

    doc.text(
      "• " + item,
      25,
      y
    );

    y += 8;

  });

  y += 10;

  /* -----------------------
     Recommendation
  ----------------------- */

  doc.setFontSize(16);

  doc.text(
    "AI Recommendation",
    20,
    y
  );

  y += 10;

  doc.setFontSize(11);

  result.recommendations?.forEach((item:string)=>{

    doc.text(
      "• " + item,
      25,
      y
    );

    y += 8;

  });

  /* -----------------------
     Footer
  ----------------------- */

  doc.setDrawColor(37,99,235);

  doc.line(
    20,
    280,
    190,
    280
  );

  doc.setFontSize(10);

  doc.text(
    "Generated by AI Voice Scam Detection System",
    20,
    287
  );

  doc.save(
    "AI_Voice_Scam_Report.pdf"
  );

};